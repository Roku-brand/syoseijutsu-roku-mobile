function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

for (const card of source.cards) {
  const text = [card.title, card.body, card.explanation].filter(Boolean).join(" ");
  const specificTags = keywordRules.flatMap(([pattern, tags]) =>
    pattern.test(text) ? tags : [],
  );
  const editorialTags = (card.tags ?? []).filter((tag) => editorialTagSet.has(tag));
  card.tags = unique([
    forcedPersonaById[card.id],
    ...editorialTags,
    ...(subcategoryTags[card.subcategory] ?? []),
    ...specificTags,
    ...(categoryTags[card.category] ?? []),
  ]).slice(0, 12);
}

