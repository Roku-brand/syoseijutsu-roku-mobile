import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import ts from 'typescript';

const legal = new URL('../src/data/legal-documents.ts', import.meta.url);
const legalModule = { exports: {} };
const loadSource = new Function('require', 'module', 'exports', ts.transpileModule(readFileSync(legal, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, esModuleInterop: true, ignoreDeprecations: '6.0' },
}).outputText);
loadSource(createRequire(legal), legalModule, legalModule.exports);
const { privacy } = legalModule.exports.getLegalDocuments();
const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const markdown = [
  '# ' + privacy.title, privacy.lead,
  ...privacy.sections.flatMap(section => [
    '## ' + section.title, ...section.paragraphs,
    (section.links ?? []).map(link => '[' + link.title + '](' + link.url + ')').join('\n'),
  ]),
].filter(Boolean).join('\n\n') + '\n';
const html = `<!doctype html>
<!-- Generated by scripts/sync-privacy-documents.mjs -->
<html lang="ja">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escape(privacy.title)}｜処世術禄</title>
  <style>
    body { margin: 0; color: #181914; background: #f4f0e7; font: 1rem/1.9 -apple-system, BlinkMacSystemFont, "Yu Gothic", sans-serif; }
    main { width: min(760px, calc(100% - 40px)); margin: 0 auto; padding: 48px 0 72px; }
    h1 { font: 500 clamp(2rem, 6vw, 3rem)/1.4 "Yu Mincho", serif; }
    h2 { font-size: 1.15rem; margin-top: 36px; }
    a { color: #69481f; }
  </style>
</head>
<body>
<main>
  <h1>${escape(privacy.title)}</h1>
  <p>${escape(privacy.lead)}</p>
${privacy.sections.map(section => [
  '  <section>', '    <h2>' + escape(section.title) + '</h2>',
  ...section.paragraphs.map(paragraph => '    <p>' + escape(paragraph) + '</p>'),
  ...(section.links ?? []).map(link => '    <p><a href="' + escape(link.url) + '">' + escape(link.title) + '</a></p>'),
  '  </section>',
].join('\n')).join('\n')}
</main>
</body>
</html>
`;
for (const [path, expected] of [
  ['PRIVACY_POLICY.md', markdown],
  ['public/privacy/index.html', html],
  ['store/privacy/index.html', html],
]) {
  const output = new URL('../' + path, import.meta.url);
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8').replaceAll('\r\n', '\n') !== expected) throw new Error(path + ' is out of sync with legal-documents.ts');
  } else {
    writeFileSync(output, expected);
  }
}
