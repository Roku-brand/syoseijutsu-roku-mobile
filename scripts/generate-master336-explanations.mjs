function pick(values, index, offset = 0) {
  return values[(index * 7 + offset) % values.length];
}

function focusFor(title, field) {
  if (/会話|聞|質問|話題|沈黙|返信|言葉/.test(title)) return '会話の内容ではなく、相手が話し続けてもよいと感じられる空気';
  if (/信頼|約束|秘密|報告|謝|連絡/.test(title)) return '小さな場面で見える一貫性';
  if (/断|距離|境界|無礼|不機嫌|離れ/.test(title)) return '許される範囲を相手へどう伝えるか';
  if (/交渉|条件|譲|選択肢|合意|価格/.test(title)) return '相手が受け入れても立場を失わない着地点';
  if (/締切|時間|予定|タスク|優先|完了/.test(title)) return '次に動く人が迷わない仕事の区切り';
  if (/不安|失敗|後悔|怖|回復|焦/.test(title)) return '感情が強いときに判断を極端にしないこと';
  if (/目標|未来|選択|決断|可能性|挑戦|成長/.test(title)) return '今の選択を将来の余地につなげること';
  return field === 'interpersonal' ? '相手にどう受け取られるか' : field === 'work' ? '周囲がどう動ける状態になるか' : '自分の選択肢をどう残すか';
}

