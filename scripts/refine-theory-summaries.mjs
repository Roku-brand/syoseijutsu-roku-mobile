async function refine(pathname) {
  const records = JSON.parse(await readFile(pathname, 'utf8'));
  replacements.forEach(([expectedTitle, summary], index) => {
    const tagId = `kb_${String(index + 387).padStart(3, '0')}`;
    const record = records.find((item) => item.tagId === tagId);
    if (!record) {
      throw new Error(`${path.relative(ROOT, pathname)}: missing ${tagId}`);
    }
    if (record.title !== expectedTitle) {
      throw new Error(
        `${record.tagId}: expected title "${expectedTitle}", found "${record.title}"`,
      );
    }
    record.summary = summary;
  });

  await writeFile(pathname, `${JSON.stringify(records, null, 2)}\n`, 'utf8');
  return replacements.length;
}

