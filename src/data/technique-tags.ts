import type { TechniqueSource } from './types';

type TechniqueContext = TechniqueSource & {
  categoryName: string;
  subcategory: string;
  articleTitle: string;
};

// 「〇〇な人」は検索タグではなく、subcategory/articleTitle の階層で表す。
// 既存の完全版データに混ざっている人物像タグも、ここで表示・検索対象から外す。
function isStructuralTag(tag: string, card: TechniqueContext) {
  return tag === card.categoryName
    || tag === card.subcategory
    || tag === card.articleTitle
    || /人$/.test(tag);
}

