export function getTechniqueTags(card: TechniqueContext) {
  const text = [card.title, card.subtitle, card.explanation].filter(Boolean).join(' ');
  const tags = [
    ...(card.tags ?? []).filter((tag) => !isStructuralTag(tag, card)),
    ...(categoryContext[card.categoryName] ?? []),
    ...(subcategoryContext[card.subcategory] ?? []),
    ...tagRules.flatMap(([pattern, values]) => (pattern.test(text) ? values : [])),
  ];

  const unique = [...new Set(tags)].filter((tag) => !isStructuralTag(tag, card));
  // 8〜12個の検索語を揃え、検索結果の再現率をカードごとに安定させる。
  return unique.slice(0, 12);
}

export function getTechniqueSearchText(card: TechniqueContext) {
  return [
    card.title,
    card.subtitle,
    card.explanation,
    card.categoryName,
    card.subcategory,
    card.articleTitle,
    ...getTechniqueTags(card),
  ]
    .filter(Boolean)
    .join(' ')
    .toLocaleLowerCase();
}
